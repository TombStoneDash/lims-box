import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const read = async name => import(pathToFileURL(`${process.cwd()}/lib/ohworks-${name}.ts`).href);
const { evaluateReferenceRange } = await read('reference-range');
const { formatReportedResult } = await read('reporting-format');
const { decideTestCancellation } = await read('test-cancellation');
const { evaluateCalibrationVerificationSchedule } = await read('calibration-verification');
const { evaluateCriticalRepeat } = await read('critical-repeat');
const { mapInstrumentFlags } = await read('instrument-flags');
const observations = [];
const range = { unit:'mg/L', limitOfDetection:1, upperLimitOfQuantitation:100, referenceRange:{lowerBound:5,upperBound:20,unit:'mg/L'} };
const reference = evaluateReferenceRange({...range,result:'0x10'});
assert.equal(reference.classification, 'within_range');
assert.equal(evaluateReferenceRange({...range,result:'invalid'}).classification, 'invalid');
observations.push({id:1,input:'result=0x10; reference range 5..20',observed:reference,expected:'invalid, not a converted decimal result'});
const format = {analyteCode:'SYNTH-A', unit:'mg/L',decimalPlaces:2,belowDetectionSymbol:'<',belowDetectionLimit:100,aboveQuantitationSymbol:'>',aboveQuantitationLimit:1,qualitativeThresholds:null};
const report = formatReportedResult({analyteCode:'SYNTH-A',value:50,formats:[format]});
assert.equal(report.reportString, '<100 mg/L');
assert.equal(formatReportedResult({analyteCode:'SYNTH-A',value:50,formats:[{...format,belowDetectionLimit:1,aboveQuantitationLimit:100}]}).reportString,'50.00 mg/L');
observations.push({id:2,input:'value=50; LOD=100; ULOQ=1',observed:report,expected:'typed formats-malformed refusal for inverted limits'});
const cancellation = decideTestCancellation({orderReferenceToken:'   ',stage:'reported',reasonCode:'lab_processing_error',requesterRole:'lab_director'});
assert.equal(cancellation.outcome,'allowed');
assert.equal(cancellation.amendedReportRequired,true);
assert.throws(()=>decideTestCancellation({orderReferenceToken:'',stage:'reported',reasonCode:'lab_processing_error',requesterRole:'lab_director'}),{code:'order-reference-token-invalid'});
observations.push({id:3,input:'whitespace-only order reference',observed:cancellation,expected:'order-reference-token-invalid'});
const schedule = {instrumentId:'SYNTH-I',analyteId:'SYNTH-A',lastVerifiedAt:'2026-01-01T00:00:00Z',maxIntervalDays:30,triggerEvents:[{kind:'reagent-lot-change',occurredAt:'2026-02-01T00:00:00Z'}]};
const calibration = evaluateCalibrationVerificationSchedule(schedule,'2026-01-10T00:00:00Z');
assert.equal(calibration.decision,'REQUIRED_BY_EVENT');
assert.equal(evaluateCalibrationVerificationSchedule({...schedule,triggerEvents:[]},'2026-01-10T00:00:00Z').decision,'CURRENT');
observations.push({id:4,input:schedule,asOf:'2026-01-10T00:00:00Z',observed:calibration,expected:'reject future-dated recorded event, not a valid trigger-event-required finding'});
const first = {subjectId:'SYNTH-S',analyteCode:'SYNTH-A',unit:'mmol/L',value:'0x10',capturedAt:'2026-01-02T12:00:00Z'};
const repeatInput = {first,repeats:[{...first,value:16,capturedAt:'2026-01-02T12:15:00Z'}],policy:{analyteCode:'SYNTH-A',unit:'mmol/L',repeatRequired:true,tolerance:{absolute:0.5,percent:10},maxRepeats:2}};
const repeat = evaluateCriticalRepeat(repeatInput);
assert.equal(repeat.status,'confirmed');
assert.equal(repeat.reportValue,16);
assert.equal(evaluateCriticalRepeat({...repeatInput,first:{...first,value:'invalid'}}).status,'discordant');
observations.push({id:5,input:repeatInput,observed:repeat,expected:'discordant first-result-value-invalid, no report value'});
const flags = mapInstrumentFlags({},'__proto__',[]);
assert.equal(flags.decision,'mapped');
assert.equal(flags.reasonCode,'no-raw-flags');
assert.equal(mapInstrumentFlags({},'SYNTH-UNKNOWN',[]).decision,'blocked');
observations.push({id:6,input:'empty mapping table, model=__proto__, no raw flags',observed:flags,expected:'blocked unknown-instrument-model'});
console.log(JSON.stringify({verifiedDefects:observations.length,observations},null,2));
