/**
 * Heuristic triage only: categories do not establish ownership or reuse rights.
 * Only extension, path and first line influence classification; size is metadata.
 * Rules are ordered: unavailable sample, attribution, media, generated, drafts,
 * code, document, unknown. Sensitive paths override risk after categorization.
 * Reasons are fixed strings and never echo sampled content.
 */
export function classifyFile({ relPath = '', ext = '', sizeBytes, firstLineText } = {}) {
  const name = String(relPath).replaceAll('\\', '/').toLowerCase();
  const extension = String(ext).toLowerCase().replace(/^([^\.])/, '.$1');
  const result = (category, riskLevel, reason) => {
    const reasons = [reason];
    // Any path substring invoice/contract/nda/license raises risk to high,
    // including otherwise unknown files; intentional false positives are safe.
    if (/invoice|contract|nda|license/i.test(name)) {
      riskLevel = 'high';
      reasons.push('Sensitive path term requires rights review.');
    }
    return { category, riskLevel, reasons };
  };

  // Missing/unreadable/binary samples must not gain a reassuring classification.
  if (typeof firstLineText !== 'string') {
    return result('unknown', 'unknown', 'First-line text is unavailable or binary.');
  }
  // Leading attribution on Markdown/plain text takes precedence over draft names.
  if (['.md', '.txt'].includes(extension) && /^(copyright|\u00a9|all rights reserved|licensed under)/i.test(firstLineText)) {
    return result('third-party-document', 'high', 'First line starts with an attribution or rights marker.');
  }
  // Media extensions or stock-photo names indicate assets needing source review.
  if (['.psd', '.ai', '.indd', '.png', '.jpg', '.jpeg', '.gif', '.svg', '.webp', '.mp3', '.wav', '.mp4', '.mov'].includes(extension) || /stock[-_ ]?photo/.test(name)) {
    return result('media-asset', 'medium', 'Media extension or stock-photo path marker.');
  }
  // Export path markers or explicit generated first-line markers indicate exports.
  if (/(^|[/_. -])exports?([/_. -]|$)/.test(name) || /^(generated by|auto-generated|automatically generated)/i.test(firstLineText)) {
    return result('generated-export', 'medium', 'Export path or generated first-line marker.');
  }
  // Draft/notes/journal path substrings plus these editable extensions suggest
  // own writing only after stronger signals above; this is not ownership proof.
  if (['.ts', '.js', '.py', '.json', '.md', '.txt'].includes(extension) && /draft|notes|journal/.test(name)) {
    return result('own-writing', 'low', 'Editable text in a draft, notes or journal path; ownership unverified.');
  }
  // Recognized source/config extensions alone are medium, never presumed owned.
  if (['.ts', '.js', '.mjs', '.cjs', '.tsx', '.jsx', '.py', '.json', '.yaml', '.yml', '.toml', '.ini'].includes(extension)) {
    return result('code-or-config', 'medium', 'Recognized source-code or configuration extension.');
  }
  // Document containers conservatively require third-party source review.
  if (['.pdf', '.doc', '.docx', '.ppt', '.pptx', '.epub'].includes(extension)) {
    return result('third-party-document', 'medium', 'Document container extension; source rights unverified.');
  }
  // Deliberate fallback: no evidence is never evidence of low risk.
  return result('unknown', 'unknown', 'No recognized provenance signal.');
}
